export async function POST(req: NextRequest) {
  try {
    const body = await req.json();
    const query = (body.query || '').trim();
    const apiKey = (body.apiKey || process.env.GEMINI_API_KEY || '').trim();
    const history = body.history || [];

    if (!query) {
      return NextResponse.json({ reply: '質問内容を入力してください。' }, { status: 400 });
    }

    // Google Gemini API呼び出し（APIキー設定時）
    if (apiKey) {
      try {
        const contents = [
          ...history.map((h: { sender: string; text: string }) => ({
            role: h.sender === 'user' ? 'user' : 'model',
            parts: [{ text: h.text }]
          })),
          {
            role: 'user',
            parts: [{ text: query }]
          }
        ];

        // gemini-1.5-flash または gemini-2.0-flash を利用
        const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${apiKey}`;
        const res = await fetch(geminiUrl, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            system_instruction: {
              parts: [{ text: SYSTEM_PROMPT }]
            },
            contents,
            generationConfig: {
              temperature: 0.2,
              maxOutputTokens: 1200
            }
          })
        });

        if (res.ok) {
          const data = await res.json();
          const candidateText = data?.candidates?.[0]?.content?.parts?.[0]?.text;
          if (candidateText) {
            return NextResponse.json({
              reply: candidateText,
              source: 'gemini'
            });
          }
        } else {
          console.warn('Gemini API call failed with status:', res.status);
        }
      } catch (err) {
        console.warn('Gemini API call error:', err);
      }
    }

    // APIキー未設定またはGemini呼び出し失敗時はローカルエンジンで即時回答
    const localReply = answerLocally(query);
    return NextResponse.json({
      reply: localReply,
      source: 'local'
    });
  } catch (error) {
    return NextResponse.json({
      reply: 'エラーが発生しました。もう一度入力してください。'
    }, { status: 500 });
  }
}

